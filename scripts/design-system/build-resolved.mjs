// The artefacts the SwiftUI port reads. `node scripts/design-system/build-resolved.mjs`
//   docs/design-system/resolved/<theme>.json   one theme at size M / normal density, every reference resolved, per mode,
//                                              plus the size scale and density factors (the port applies those two itself).
//   Sources/LupitaCore/Theme/ThemeData.generated.swift      the same documents, embedded (no bundle resources in the app).
//   Tests/LupitaCoreTests/ThemeExpected.generated.swift     what the port must compute for EVERY theme × size × density × mode
//                                              (the JS loader is the reference; the Swift arithmetic is tested against it).
import { mkdirSync, writeFileSync, readFileSync, rmSync, readdirSync } from 'node:fs'
import { DS, ROOT, SIZES, DENSITIES, listThemes, loadTheme } from './lib.mjs'

// Menu order: the default first, then the characters.
const ORDER = ['cristal', 'papel', 'terminal', 'neon', 'brutalista', 'ficha', 'blueprint']
const ids = listThemes()
if (JSON.stringify([...ORDER].sort()) !== JSON.stringify(ids)) throw new Error(`ORDER ${ORDER} does not match themes ${ids}`)

const camel = s => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const base = JSON.parse(readFileSync(`${DS}/tokens.json`, 'utf8'))
const ROLES = Object.keys(base.semantic.text)
const SPACE = Object.keys(base.semantic.space)
const COLORS = Object.keys(base.semantic.color).filter(k => !['surface-blur', 'suggestion-opacity'].includes(k))
const sizeClass = role => base.semantic.text[role].size.match(/font\.size\.(\w+)/)[1] // heading | body | code | label

function modeDoc(t, mode) {
  const m = t[mode], baseT = loadTheme(t.id) // M / normal
  const text = {}
  for (const r of ROLES) {
    const v = m[`text.${r}`]
    text[r] = { font: v.familyKey, size: sizeClass(r), weight: v.weight, italic: v.italic, lineHeight: v.lineHeight, tracking: v.tracking, color: v.color }
  }
  const o = {
    text,
    color: Object.fromEntries(COLORS.map(k => [camel(k), m[`color.${k}`]])),
    surfaceBlur: m['color.surface-blur'], suggestionOpacity: m['color.suggestion-opacity'],
    radius: Object.fromEntries(Object.keys(base.semantic.radius).map(k => [k, m[`radius.${k}`]])),
    border: Object.fromEntries(Object.keys(base.semantic.border).map(k => [k, m[`border.${k}`]])),
    space: Object.fromEntries(SPACE.map(k => [camel(k), m[`space.${k}`]])),
    shadow: { container: m['shadow.container'], notice: m['shadow.notice'], inset: m['shadow.inset'] },
  }
  return o
}

mkdirSync(`${DS}/resolved`, { recursive: true })
for (const f of readdirSync(`${DS}/resolved`)) if (f.endsWith('.json') && !ids.includes(f.slice(0, -5))) rmSync(`${DS}/resolved/${f}`)
const docs = {}
for (const id of ORDER) {
  const t = loadTheme(id)
  if (t.errors.length) throw new Error(`${id}: ${t.errors.join('; ')}`)
  const doc = {
    id, name: t.name, blurb: t.blurb,
    fonts: Object.fromEntries(['heading', 'body', 'code'].map(r => [r, t.light[`font.family.${r}`]])),
    light: modeDoc(t, 'light'), dark: modeDoc(t, 'dark'),
  }
  docs[id] = doc
  writeFileSync(`${DS}/resolved/${id}.json`, JSON.stringify(doc, null, 1) + '\n')
}
const shared = {
  scale: Object.fromEntries(SIZES.map(s => [s, base.scale[s]])),
  density: Object.fromEntries(DENSITIES.map(d => [d, base.density[d]])),
  limits: Object.fromEntries(Object.entries(base.component.limits).map(([k, v]) => [camel(k), v])),
}
writeFileSync(`${DS}/resolved/_shared.json`, JSON.stringify(shared, null, 1) + '\n')

const lit = s => `#"""\n${s}\n"""#`
const swift = `// GENERATED by scripts/design-system/build-resolved.mjs from docs/design-system. Do not edit.
enum ThemeData {
    static let order = ${JSON.stringify(ORDER)}
    static let shared = ${lit(JSON.stringify(shared))}
    static let documents: [String: String] = [
${ORDER.map(id => `        "${id}": ${lit(JSON.stringify(docs[id]))},`).join('\n')}
    ]
}
`
mkdirSync(`${ROOT}/Sources/LupitaCore/Theme`, { recursive: true })
writeFileSync(`${ROOT}/Sources/LupitaCore/Theme/ThemeData.generated.swift`, swift)

// Expected values for every combination: a flat «key=value;…» digest per (theme, mode, size, density).
const rows = []
for (const id of ORDER) for (const size of SIZES) for (const density of DENSITIES) {
  const t = loadTheme(id, { size, density })
  for (const mode of ['light', 'dark']) {
    const m = t[mode], d = []
    d.push(`width=${m['size.width']}`, `swatch=${m['size.swatch']}`)
    for (const r of ROLES) d.push(`${r}.size=${m[`text.${r}`].size}`)
    for (const k of SPACE) d.push(`space.${camel(k)}=${m[`space.${k}`]}`)
    rows.push(`${id}/${mode}/${size}/${density}\t${d.join(';')}`)
  }
}
mkdirSync(`${ROOT}/Tests/LupitaCoreTests`, { recursive: true })
writeFileSync(`${ROOT}/Tests/LupitaCoreTests/ThemeExpected.generated.swift`, `// GENERATED by scripts/design-system/build-resolved.mjs. Do not edit.
// One line per theme/mode/size/density: the numbers the JS loader computes; ThemeMatrixTests checks the Swift port against them.
enum ThemeExpected {
    static let lines = ${lit(rows.join('\n'))}
}
`)
console.log(`resolved: ${ORDER.length} themes, ${rows.length} expected rows`)
